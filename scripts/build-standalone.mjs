// Builds the standalone single-file page from programs.json + site.css.
//
// Data flows one way now:   programs.json  ->  Astro site
//                                          ->  standalone HTML (this script)
//
// Usage: node scripts/build-standalone.mjs [outputPath]
// Default output: ../bsf-funding.html (the shareable artifact next to the repo).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import * as sass from "sass";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const out = process.argv[2]
  ? resolve(process.cwd(), process.argv[2])
  : resolve(root, "..", "bsf-funding.html");

const data = JSON.parse(readFileSync(resolve(root, "src/data/programs.json"), "utf8"));
// Compile the same SCSS partials the Astro modules use, but unhashed so the
// markup generated below can reference the class names literally.
const css = sass.compile(resolve(root, "src/styles/standalone.scss"), {
  loadPaths: [resolve(root, "src/styles")],
  style: "compressed"
}).css;

const page = `<title>Barth Syndrome Research Funding Index</title>
<style>
${css}
/* standalone-only */
.doc { padding: 32px 40px 64px; max-width: 760px; }
</style>

<div class="shell">
  <aside class="rail">
    <div>
      <div class="brandA">Barth Syndrome</div>
      <div class="brandB">Research Funding Index</div>
      <div class="headline" id="headline">$0M+</div>
      <p class="headlineNote">Max single-award total across capped programs still open. Uncapped and in-kind mechanisms add more.</p>
    </div>

    <div>
      <input type="search" id="q" class="search" placeholder="Search the index&hellip;" aria-label="Search funding programs" />
      <p class="count" id="count"></p>
    </div>

    <div>
      <div class="railHead">Funder</div>
      <div class="railList" id="cat-filters"></div>
    </div>
    <div>
      <div class="railHead">Audience</div>
      <div class="railList" id="aud-filters"></div>
    </div>
    <div>
      <div class="railHead">Status</div>
      <div class="railList" id="status-filters"></div>
    </div>

    <div class="railFoot">
      Last updated <span id="last-updated"></span>.<br />Confirm details on the funder's site before applying.
    </div>
  </aside>

  <main style="min-width: 0;">
    <div class="tblHead">
      <span class="lblMuted">No.</span>
      <button id="sort-name" type="button">Program <span class="arrow"></span></button>
      <button id="sort-award" class="taR" type="button">Award max <span class="arrow"></span></button>
      <button id="sort-deadline" class="colDeadline" type="button">Deadline <span class="arrow"></span></button>
      <span class="lblMuted taR">Src</span>
    </div>
    <div id="rows"></div>
  </main>
</div>

<div id="drawer-root"></div>

<script>
/* Generated by scripts/build-standalone.mjs — edit src/data/programs.json, not this file. */
const DATA = ${JSON.stringify(data)};
const LAST_UPDATED = DATA.lastUpdated;
const AWARD_MAX_USD = DATA.awardMaxUSD;
const PROGRAMS = DATA.programs;

const CAT_META = {
  government: { code: "GOV", label: "Government" },
  nonprofit: { code: "FDN", label: "Foundation / non-profit" },
  corporate: { code: "CORP", label: "Corporate / industry" },
  general: { code: "GEN", label: "General biomedical" }
};

function slugify(name) {
  return name.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "").slice(0, 80).replace(/-+$/g, "");
}
for (const p of PROGRAMS) p.slug = slugify(p.name);

const srcClass = cat => "src" + cat.charAt(0).toUpperCase() + cat.slice(1);

const rowsEl = document.getElementById("rows");
const countEl = document.getElementById("count");
const qEl = document.getElementById("q");
const drawerRoot = document.getElementById("drawer-root");
let state = { q: "", cat: "all", aud: null, showPast: false, sort: "award", dir: "desc" };

const esc = s => String(s ?? "").replace(/[&<>"']/g, c =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

function highlight(text, terms) {
  let out = esc(text);
  for (const t of terms) {
    const re = new RegExp("(" + t.replace(/[.*+?^\${}()|[\\]\\\\]/g, "\\\\$&") + ")", "gi");
    out = out.replace(re, "<mark>$1</mark>");
  }
  return out;
}

const hay = p => [p.name, p.sponsor, p.desc, p.eligibility, p.apply, p.amount, p.deadline,
  (p.tags || []).join(" ")].join(" ").toLowerCase();

const audPass = (p, a) => {
  if (!a) return true;
  const tags = p.tags || [];
  const isOrg = tags.includes("for organizations");
  return a === "orgs" ? isOrg : (!isOrg || tags.includes("for researchers"));
};

function parseDeadline(s) {
  if (!s) return Infinity;
  const m = String(s).match(/(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z.]*\\s+(\\d{1,2}),?\\s+(\\d{4})/);
  if (m) return new Date(m[3] + " " + m[1] + " " + m[2]).getTime();
  const y = String(s).match(/\\b(20\\d\\d)\\b/);
  if (y) return new Date(y[1] + "-06-30").getTime();
  return Infinity;
}

function fmtUSD(v) {
  if (!v) return "\\u2014";
  if (v >= 1e6) return "$" + (Math.round(v / 1e5) / 10).toFixed(v % 1e6 ? 1 : 0).replace(/\\.0$/, "") + "M";
  return "$" + Math.round(v / 1e3) + "K";
}

const shortDeadline = s => {
  if (!s) return "\\u2014";
  const t = String(s);
  return t.length > 64 ? t.slice(0, 61).replace(/[,;\\s]+\\S*$/, "") + "\\u2026" : t;
};

const terms = () => state.q.trim().toLowerCase().split(/\\s+/).filter(Boolean);

function pool(opts = {}) {
  const t = terms();
  return PROGRAMS.filter(p => {
    if (p.expired && !state.showPast && !opts.ignorePast) return false;
    if (!opts.ignoreCat && state.cat !== "all" && p.cat !== state.cat) return false;
    if (!opts.ignoreAud && !audPass(p, state.aud)) return false;
    return t.every(x => hay(p).includes(x));
  });
}

function sortRows(list) {
  const sgn = state.dir === "asc" ? 1 : -1;
  return list.slice().sort((a, b) => {
    if (state.sort === "name") return sgn * a.name.localeCompare(b.name);
    if (state.sort === "award") {
      const av = AWARD_MAX_USD[a.name] || 0, bv = AWARD_MAX_USD[b.name] || 0;
      return sgn * (av - bv) || a.name.localeCompare(b.name);
    }
    const ad = parseDeadline(a.deadline), bd = parseDeadline(b.deadline);
    if (ad === bd) return a.name.localeCompare(b.name);
    if (ad === Infinity) return 1;
    if (bd === Infinity) return -1;
    return sgn * (ad - bd);
  });
}

function renderRail() {
  const catBase = pool({ ignoreCat: true });
  const cats = [["all", "All sources"], ["government", "Government"], ["nonprofit", "Foundations"],
    ["corporate", "Corporate"], ["general", "General biomedical"]];
  document.getElementById("cat-filters").innerHTML = cats.map(([key, label]) => \`
    <button class="railBtn" data-cat="\${key}" aria-pressed="\${state.cat === key}" type="button">
      <span>\${label}</span><span class="n">\${catBase.filter(p => key === "all" || p.cat === key).length}</span>
    </button>\`).join("");

  const audBase = pool({ ignoreAud: true });
  const auds = [["", "Everyone"], ["researchers", "Researchers"], ["orgs", "Advocacy orgs"]];
  document.getElementById("aud-filters").innerHTML = auds.map(([key, label]) => \`
    <button class="railBtn" data-aud="\${key}" aria-pressed="\${(state.aud || "") === key}" type="button">
      <span>\${label}</span><span class="n">\${audBase.filter(p => audPass(p, key || null)).length}</span>
    </button>\`).join("");

  document.getElementById("status-filters").innerHTML = \`
    <button class="railBtn" data-past="1" aria-pressed="\${state.showPast}" type="button">
      <span>Include past programs</span><span class="n">\${PROGRAMS.filter(p => p.expired).length}</span>
    </button>\`;

  document.querySelectorAll("[data-cat]").forEach(b => b.onclick = () => { state.cat = b.dataset.cat; render(); });
  document.querySelectorAll("[data-aud]").forEach(b => b.onclick = () => { state.aud = b.dataset.aud || null; render(); });
  document.querySelector("[data-past]").onclick = () => { state.showPast = !state.showPast; render(); };
}

function render() {
  const t = terms();
  const list = sortRows(pool());
  const poolCount = PROGRAMS.filter(p => !p.expired || state.showPast).length;

  countEl.textContent = (list.length === poolCount
    ? poolCount + " PROGRAMS"
    : list.length + " OF " + poolCount + " PROGRAMS")
    + (state.showPast ? "" : " \\u00b7 " + PROGRAMS.filter(p => p.expired).length + " PAST HIDDEN");

  rowsEl.innerHTML = list.length ? list.map((p, i) => {
    const meta = CAT_META[p.cat] || { code: "\\u2014" };
    return \`
    <button class="row\${p.expired ? " isPast" : ""}" data-slug="\${esc(p.slug)}" type="button">
      <span class="num">\${String(i + 1).padStart(2, "0")}</span>
      <span style="min-width:0">
        <span class="name">\${highlight(p.name, t)}\${p.expired ? '<span class="tagPast">PAST</span>' : ""}</span>
        <span class="sponsor">\${highlight(p.sponsor, t)}</span>
        <span class="deadlineInline">\${highlight(shortDeadline(p.deadline), t)}</span>
      </span>
      <span class="award">\${fmtUSD(AWARD_MAX_USD[p.name])}</span>
      <span class="deadline colDeadline">\${highlight(shortDeadline(p.deadline), t)}</span>
      <span class="src \${srcClass(p.cat)}">\${meta.code}</span>
    </button>\`;
  }).join("") : '<div class="empty"><strong>No programs match.</strong>Try a broader term \\u2014 \\u201cmitochondrial\\u201d, \\u201cpilot\\u201d, or \\u201cfellowship\\u201d.</div>';

  rowsEl.querySelectorAll(".row").forEach(r => { r.onclick = () => { location.hash = r.dataset.slug; }; });

  const arrows = { name: "sort-name", award: "sort-award", deadline: "sort-deadline" };
  for (const key in arrows) {
    document.querySelector("#" + arrows[key] + " .arrow").textContent =
      state.sort === key ? (state.dir === "asc" ? "\\u2191" : "\\u2193") : "";
  }
  renderRail();
}

function setSort(s) {
  if (state.sort === s) state.dir = state.dir === "asc" ? "desc" : "asc";
  else { state.sort = s; state.dir = s === "award" ? "desc" : "asc"; }
  render();
}
document.getElementById("sort-name").onclick = () => setSort("name");
document.getElementById("sort-award").onclick = () => setSort("award");
document.getElementById("sort-deadline").onclick = () => setSort("deadline");
qEl.addEventListener("input", () => { state.q = qEl.value; render(); });

function renderDrawer() {
  const slug = decodeURIComponent(location.hash.replace(/^#/, ""));
  const p = PROGRAMS.find(x => x.slug === slug);
  if (!p) { drawerRoot.innerHTML = ""; document.body.style.overflow = ""; return; }
  const meta = CAT_META[p.cat] || { code: "\\u2014", label: "" };
  drawerRoot.innerHTML = \`
    <button class="scrim" id="scrim" aria-label="Close details" type="button"></button>
    <div class="drawer" role="dialog" aria-modal="true" aria-label="\${esc(p.name)}">
      <div class="drawerTop">
        <span class="drawerCat \${srcClass(p.cat)}">\${meta.code} \\u2014 \${esc(meta.label.toUpperCase())}</span>
        <button class="drawerClose" id="drawer-close" type="button">Close \\u2715</button>
      </div>
      <h2>\${esc(p.name)}</h2>
      <p class="sponsor">\${esc(p.sponsor)}</p>
      \${p.expired ? '<div class="pastBanner">This application window has closed. Kept for reference \\u2014 check the funder\\'s page for a future cycle.</div>' : ""}
      <div class="facts">
        <div class="fact"><div class="factK">Award</div><div class="factV">\${esc(p.amount || "\\u2014")}</div></div>
        <div class="fact"><div class="factK">Deadline</div><div class="factV">\${esc(p.deadline || "\\u2014")}</div></div>
      </div>
      <p class="lede">\${esc(p.desc)}</p>
      <div class="sec"><div class="secH">Who can apply</div><p>\${esc(p.eligibility)}</p></div>
      <div class="sec"><div class="secH">How to apply</div><p>\${esc(p.apply)}</p></div>
      <div class="sec">
        <div class="secH">Links</div>
        <div class="links">
          \${(p.links || []).map(l => \`<a href="\${esc(l.url)}" target="_blank" rel="noopener">\${esc(l.label)} \\u2197</a>\`).join("")}
        </div>
      </div>
    </div>\`;
  document.body.style.overflow = "hidden";
  const close = () => { history.pushState("", document.title, location.pathname + location.search); renderDrawer(); };
  document.getElementById("scrim").onclick = close;
  document.getElementById("drawer-close").onclick = close;
}
window.addEventListener("hashchange", renderDrawer);
window.addEventListener("keydown", e => {
  if (e.key === "Escape" && location.hash) {
    history.pushState("", document.title, location.pathname + location.search);
    renderDrawer();
  }
});

const expiredNames = new Set(PROGRAMS.filter(p => p.expired).map(p => p.name));
const totalUSD = Object.entries(AWARD_MAX_USD)
  .filter(([name]) => !expiredNames.has(name))
  .reduce((sum, [, v]) => sum + v, 0);
document.getElementById("headline").textContent = "$" + Math.floor(totalUSD / 1e6) + "M+";
document.getElementById("last-updated").textContent = LAST_UPDATED;

render();
renderDrawer();
</script>
`;

writeFileSync(out, page);
console.log(`standalone written: ${out}`);
console.log(`  programs: ${data.programs.length}, last updated: ${data.lastUpdated}`);
